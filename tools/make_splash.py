"""Downsample the approved square splash and pack its 4-bit grayscale pixels."""
from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SIZE = 240


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=ROOT / "assets/splash/terkinstein-splash-master.png")
    parser.add_argument("--png", type=Path, default=ROOT / "assets/splash/terkinstein-splash-240.png")
    parser.add_argument("--header", type=Path, default=ROOT / "firmware/gen/terkinstein_splash.h")
    args = parser.parse_args()

    with Image.open(args.input) as source:
        if source.width != source.height or source.width < SIZE:
            parser.error("Input must be a square image at least 240 pixels wide.")
        rgba = source.convert("RGBA")
        opaque = Image.new("RGBA", rgba.size, (0, 0, 0, 255))
        opaque.alpha_composite(rgba)
        gray = opaque.convert("L").resize((SIZE, SIZE), Image.Resampling.LANCZOS)

    # Sixteen levels keep the small logo's antialiased edges, at two pixels/byte.
    levels = bytes(min(15, (value + 8) // 17) for value in gray.tobytes())
    packed = bytes((levels[i] << 4) | levels[i + 1] for i in range(0, len(levels), 2))
    preview = Image.frombytes("L", (SIZE, SIZE), bytes(value * 17 for value in levels))
    args.png.parent.mkdir(parents=True, exist_ok=True)
    preview.save(args.png, compress_level=9)

    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-only */",
        "/* Generated by tools/make_splash.py. High nibble is the left pixel.",
        " * User-supplied TERKINSTEIN artwork, adapted for the FM-1 splash. */",
        "#ifndef TERKINSTEIN_SPLASH_H",
        "#define TERKINSTEIN_SPLASH_H",
        "#include <stdint.h>",
        f"#define TK_SPLASH_WIDTH {SIZE}",
        f"#define TK_SPLASH_HEIGHT {SIZE}",
        f"static const uint8_t tk_splash_pixels[{len(packed)}] = {{",
    ]
    for offset in range(0, len(packed), 16):
        lines.append("    " + ", ".join(f"0x{value:02x}" for value in packed[offset:offset + 16]) + ",")
    lines.extend(["};", "#endif", ""])
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Splash: {SIZE} x {SIZE}, 16 grays, {len(packed):,} bytes in flash")
    print(args.png)
    print(args.header)


if __name__ == "__main__":
    main()
